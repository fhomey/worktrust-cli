/** Native runner smoke: create/read/delete ONE disposable vault entry; no real coupling or credentials. */
import assert from 'node:assert/strict';
import { mkdtempSync, readFileSync, rmSync, mkdirSync, readdirSync, statSync, existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import { generateKeyPairSync, sign, verify } from 'node:crypto';
import { createServer } from 'node:http';
import { createInterface } from 'node:readline';
import { once } from 'node:events';
import { writeFileSync } from 'node:fs';
import { spawn, spawnSync } from 'node:child_process';
const source = resolve(process.env.WORKTRUST_TEST_CLI_SOURCE || 'apps/worktrust/app/public/counter');
const { createCredentialStore, readDeviceSigningKey } = await import(pathToFileURL(join(source, 'credential-store.mjs')));
const { nativeKeyStore } = await import(pathToFileURL(join(source, 'credential-vault.mjs')));
const root = mkdtempSync(join(tmpdir(), 'wt-native-vault-')), file = join(root, '.worktrust', 'key.json');
const vault = nativeKeyStore(), store = createCredentialStore(file, vault);
let id; let bridge; let server;
try {
  const pair = generateKeyPairSync('ed25519');
  const fixture = { token: 'wt_disposable_not_a_real_token', device: pair.privateKey.export({type:'pkcs8',format:'pem'}), url: 'https://example.invalid/api/mcp' };
  store.save(fixture); store.protect(); id = JSON.parse(readFileSync(file, 'utf8')).id;
  assert.deepEqual(store.load(), fixture);
  const archiveSigner = readDeviceSigningKey(file), metadata = Buffer.from('synthetic metadata digest');
  assert(verify(null, metadata, pair.publicKey, sign(null, metadata, archiveSigner.privateKey)), 'offline archive reader preserves the protected device signing identity');
  const env = { HOME: root, USERPROFILE: root, PATH: process.env.PATH || '', WORKTRUST_MACHINE_ID: 'synthetic-keystore-fixture' };
  for (const name of ['SystemRoot','SYSTEMROOT','WINDIR','COMSPEC','TEMP','TMP','DBUS_SESSION_BUS_ADDRESS','XDG_RUNTIME_DIR']) if(process.env[name]) env[name]=process.env[name];
  const r = spawnSync(process.execPath, [join(source, 'worktrust.mjs'), 'status'], { env, input: '', encoding: 'utf8', timeout: 15000 });
  assert.equal(r.status, 0, `real CLI status reads protected credentials in a separate process: ${r.stderr}`);
  assert.match(r.stdout, /OS vault \+ encrypted local file/);
  assert(!r.stdout.includes(fixture.token)); assert(!r.stderr.includes(fixture.token));
  const project = join(root, '.claude', 'projects', 'fixture'); mkdirSync(project, {recursive:true});
  const started = Date.now() - 3 * 86400000;
  writeFileSync(join(project, 'session.jsonl'), [0,1,2].map(i => JSON.stringify({type:i===1?'assistant':'user', timestamp:new Date(started+i*60000).toISOString(), message:{role:i===1?'assistant':'user', content:'Synthetic fixture.', model:'synthetic', usage:{input_tokens:5,output_tokens:5}}})).join('\n')+'\n');
  const archive = join(root, 'archive'), networkLog = join(root, 'network.log'), stub = join(root, 'no-network.mjs');
  writeFileSync(stub, `import net from 'node:net'; import http from 'node:http'; import https from 'node:https'; import tls from 'node:tls'; import dns from 'node:dns'; import {appendFileSync} from 'node:fs'; import {syncBuiltinESMExports} from 'node:module';
const refuse=()=>{appendFileSync(process.env.WT_NET_LOG,'attempt\\n');throw Error('NETWORK_REFUSED');}; globalThis.fetch=refuse; net.Socket.prototype.connect=refuse; net.connect=refuse; net.createConnection=refuse; http.request=refuse; http.get=refuse; https.request=refuse; https.get=refuse; tls.connect=refuse; dns.lookup=refuse; dns.resolve=refuse; syncBuiltinESMExports();`);
  const preserve = args => spawnSync(process.execPath, [join(source, 'preserve.mjs'), ...args], {env:{...env,NODE_OPTIONS:'--import='+pathToFileURL(stub).href,WT_NET_LOG:networkLog},input:'',encoding:'utf8',timeout:30000});
  const kept = preserve(['--archive', archive]); assert.equal(kept.status, 0, kept.stderr);
  assert.equal(JSON.parse(readFileSync(join(archive, 'manifest.json'))).public_key, pair.publicKey.export({format:'jwk'}).x);
  const snapshot = dir => Object.fromEntries(readdirSync(dir).flatMap(name => { const p=join(dir,name); return statSync(p).isDirectory()?Object.entries(snapshot(p)):[[p,readFileSync(p).toString('base64')]]; }));
  const beforeArchive = snapshot(archive);
  store.save({ ...fixture, token: 'wt_rotated_disposable' }); assert.equal(store.load().token, 'wt_rotated_disposable');
  store.erase(); assert.equal(store.load(), null); assert.equal(store.protected(), true);
  let calls = 0;
  server = createServer((req, res) => { calls++; req.resume(); res.setHeader('Content-Type', 'application/json'); res.end(JSON.stringify({jsonrpc:'2.0',id:1,result:{ok:true}})); });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  store.save({ ...fixture, device: undefined, identified: true, renewedAt: new Date().toISOString(), url: `http://127.0.0.1:${server.address().port}/api/mcp` });
  writeFileSync(join(root, '.worktrust', 'bridge-swept-at'), String(Date.now()));
  bridge = spawn(process.execPath, [join(source, 'worktrust.mjs'), 'mcp'], {env, stdio: ['pipe', 'pipe', 'pipe']});
  bridge.stderr.resume();
  const replies = createInterface({input:bridge.stdout});
  const request = async id => {
    const answer = once(replies, 'line', {signal:AbortSignal.timeout(15000)});
    bridge.stdin.write(JSON.stringify({jsonrpc:'2.0', id, method:'tools/list'}) + '\n');
    return JSON.parse((await answer)[0]);
  };
  assert.equal((await request(1)).result.ok, true); assert.equal(calls, 1);
  vault.remove(id); id = null;
  const denied = await request(2);
  assert.equal(calls, 1, 'running bridge must not send a cached credential after the vault key disappears');
  assert.match(denied.error.message, /credential storage is unavailable/);
  bridge.stdin.end(); await once(bridge, 'close'); bridge = null;
  await new Promise(resolve => server.close(resolve)); server = null;
  const checked = preserve(['--verify', archive]); assert.equal(checked.status, 0, 'public archive proof verification does not require the vault: '+checked.stderr);
  const deniedArchive = preserve(['--archive', join(root,'new-archive')]); assert.notEqual(deniedArchive.status, 0);
  assert(!existsSync(join(root,'new-archive')), 'unavailable signer is refused before any archive mutation');
  assert.deepEqual(snapshot(archive), beforeArchive); assert(!existsSync(networkLog), 'protected preserve and verification stay offline');
  assert.throws(() => store.load(), /KEYSTORE_UNAVAILABLE/);
  assert.throws(() => readDeviceSigningKey(file), /KEYSTORE_UNAVAILABLE/, "archive reader cannot silently fall back when the protected key disappears");
  console.log(`PASS: native ${vault.name}: migration, separate CLI process, rotation, disconnect, missing-key refusal; synthetic entry deleted`);
} finally {
  if (bridge) bridge.kill();
  if (server) server.close();
  if (id) vault.remove(id);
  rmSync(root, { recursive: true, force: true });
}
